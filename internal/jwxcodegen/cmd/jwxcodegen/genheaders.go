package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/goccy/go-yaml"
	"github.com/lestrrat-go/codegen"
	"github.com/lestrrat-go/jwx/v4/internal/jwxcodegen"
)

// HeaderConfig holds the metadata from the YAML config file
// that controls how headers are generated for each package.
type HeaderConfig struct {
	Package                   string            `yaml:"package"`
	GeneratorComment          string            `yaml:"generator_comment"`
	OutputFile                string            `yaml:"output_file"`
	Description               string            `yaml:"description"`
	RFC                       string            `yaml:"rfc"`
	ContentNoun               string            `yaml:"content_noun"`
	HeaderComment             string            `yaml:"header_comment"`
	StoreRawOnUnmarshal       bool              `yaml:"store_raw_on_unmarshal"`
	PreFieldInterfaceMethods  []string          `yaml:"pre_field_interface_methods"`
	PostFieldInterfaceMethods []string          `yaml:"post_field_interface_methods"`
	KeysComment               string            `yaml:"keys_comment"`
	ExtraStructFields         []ExtraField      `yaml:"extra_struct_fields"`
	ExtraMethods              []ExtraMethod     `yaml:"extra_methods"`
	ZeroVals                  map[string]string `yaml:"zero_vals"`
}

// ExtraField represents an additional struct field beyond the
// standard header fields.
type ExtraField struct {
	Name    string `yaml:"name"`
	Type    string `yaml:"type"`
	Comment string `yaml:"comment"`
}

// ExtraMethod represents an additional method to generate on
// the stdHeaders struct.
type ExtraMethod struct {
	Name    string `yaml:"name"`
	Field   string `yaml:"field"`
	Returns string `yaml:"returns"`
	ArgName string `yaml:"arg_name"`
	ArgType string `yaml:"arg_type"`
	Lock    string `yaml:"lock"`
}

func runHeaders(args []string) error {
	fs := flag.NewFlagSet("generate-headers", flag.ContinueOnError)
	objectsFile := fs.String("objects", "objects.yml", "")
	if err := fs.Parse(args); err != nil {
		return err
	}

	// First pass: parse the full YAML into our config struct
	cfg, err := loadHeaderConfig(*objectsFile)
	if err != nil {
		return err
	}

	// Register zero values from config
	for typ, val := range cfg.ZeroVals {
		codegen.RegisterZeroVal(typ, val)
	}

	// Second pass: parse the fields section via yaml2json into codegen.Object
	jsonSrc, err := jwxcodegen.YAML2JSON(*objectsFile)
	if err != nil {
		return err
	}

	var object codegen.Object
	if err := json.NewDecoder(bytes.NewReader(jsonSrc)).Decode(&object); err != nil {
		return fmt.Errorf(`failed to decode %q: %w`, *objectsFile, err)
	}

	object.Organize()
	return generateHeaders(cfg, &object)
}

func loadHeaderConfig(fn string) (*HeaderConfig, error) {
	in, err := os.Open(fn)
	if err != nil {
		return nil, fmt.Errorf(`failed to open %q: %w`, fn, err)
	}
	defer in.Close()

	var cfg HeaderConfig
	if err := yaml.NewDecoder(in).Decode(&cfg); err != nil {
		return nil, fmt.Errorf(`failed to decode config from %q: %w`, fn, err)
	}
	return &cfg, nil
}

// headerFieldIsIndirect wraps FieldStorageTypeIsIndirect for use as a
// callback in shared generator functions.
func headerFieldIsIndirect(f codegen.Field) bool {
	return jwxcodegen.FieldStorageTypeIsIndirect(f)
}

// headerKeyName returns the constant name for a field's JSON key (e.g., "AlgorithmKey").
func headerKeyName(f codegen.Field) string {
	return f.Name(true) + "Key"
}

func headerHasExtraField(cfg *HeaderConfig, name string) bool {
	for _, ef := range cfg.ExtraStructFields {
		if ef.Name == name {
			return true
		}
	}
	return false
}

func generateHeaders(cfg *HeaderConfig, obj *codegen.Object) error {
	var buf bytes.Buffer

	o := codegen.NewOutput(&buf)
	o.L("// Code generated by %s. DO NOT EDIT.", cfg.GeneratorComment)
	o.LL("package %s", cfg.Package)

	o.LL(`import "encoding/json/jsontext"`)

	// const block
	o.LL("const (")
	for _, f := range obj.Fields() {
		o.L("%sKey = %q", f.Name(true), f.JSON())
	}
	o.L(")") // end const

	// Interface comment
	o.L("")
	comment := strings.TrimRight(cfg.HeaderComment, "\n")
	for _, line := range strings.Split(comment, "\n") {
		if line == "" {
			o.L("//")
		} else {
			o.L("// %s", line)
		}
	}
	o.L("type Headers interface {")

	// Getter signatures
	for _, f := range obj.Fields() {
		o.L("%s() (%s, bool)", f.GetterMethod(true), f.Type())
	}

	// Pre-field interface methods (e.g., JWS: Copy, Merge, Clone)
	for _, m := range cfg.PreFieldInterfaceMethods {
		o.L(m)
	}

	// Field/Set/Remove/Has
	o.L("// Field returns the value of a header field by name, along with a boolean indicating")
	o.L("// whether the field was found. For type-safe access, use the `%s.Get[T]()` generic accessor.", cfg.Package)
	o.L("Field(string) (any, bool)")
	o.L("Set(string, any) error")
	o.L("Remove(string) error")
	o.L("// Has returns true if the specified header has a value, even if")
	o.L("// the value is empty-ish (e.g. 0, false, \"\")  as long as it has been")
	o.L("// explicitly set.")
	o.L("Has(string) bool")

	// Post-field interface methods (e.g., JWE: Encode, Decode, Clone, Copy, Merge)
	for _, m := range cfg.PostFieldInterfaceMethods {
		o.L(m)
	}

	// Keys
	if cfg.KeysComment != "" {
		o.LL(cfg.KeysComment)
	}
	o.L("Keys() []string")

	o.L("}")

	// stdHeaderNames
	o.LL("// stdHeaderNames is a list of all standard header names defined in the %s specification.", cfg.Description[:3])
	o.L("var stdHeaderNames = []string{")
	for i, f := range obj.Fields() {
		if i > 0 {
			o.R(",")
		}
		o.R("%sKey", f.Name(true))
	}
	o.R("}")

	// struct definition
	o.LL("type stdHeaders struct {")
	for _, f := range obj.Fields() {
		if c := f.Comment(); c != "" {
			o.L("%s %s // %s", f.Name(false), jwxcodegen.FieldStorageType(f), c)
		} else {
			o.L("%s %s", f.Name(false), jwxcodegen.FieldStorageType(f))
		}
	}
	o.L("privateParams map[string]any")
	o.L("mu sync.RWMutex")
	for _, ef := range cfg.ExtraStructFields {
		if ef.Comment != "" {
			o.L("%s %s // %s", ef.Name, ef.Type, ef.Comment)
		} else {
			o.L("%s %s", ef.Name, ef.Type)
		}
	}
	o.L("}") // end type stdHeaders

	// NewHeaders
	o.LL("func NewHeaders() Headers {")
	o.L("return &stdHeaders{}")
	o.L("}")

	// Getter implementations
	for _, f := range obj.Fields() {
		o.LL("func (h *stdHeaders) %s() (%s, bool) {", f.GetterMethod(true), f.Type())
		o.L("h.mu.RLock()")
		o.L("defer h.mu.RUnlock()")
		if jwxcodegen.FieldStorageTypeIsIndirect(f) {
			o.L("if h.%s == nil {", f.Name(false))
			o.L("return %s, false", codegen.ZeroVal(f.Type()))
			o.L("}")
			o.L("return *(h.%s), true", f.Name(false))
		} else {
			o.L("return h.%s, true", f.Name(false))
		}
		o.L("}") // func (h *stdHeaders) %s() %s
	}

	// clear() method
	o.LL("func (h *stdHeaders) clear() {")
	for _, f := range obj.Fields() {
		o.L("h.%s = nil", f.Name(false))
	}
	o.L("h.privateParams = nil")
	if headerHasExtraField(cfg, "raw") {
		o.L("h.raw = nil")
	}
	o.L("}")

	// isZero() method
	o.LL("func (h *stdHeaders) isZero() bool {")
	o.L("return h.%s == nil &&", obj.Fields()[0].Name(false))
	for _, f := range obj.Fields()[1:] {
		o.L("h.%s == nil &&", f.Name(false))
	}
	o.L("len(h.privateParams) == 0")
	o.L("}")

	// Extra methods (DecodeCtx, SetDecodeCtx, rawBuffer)
	for _, em := range cfg.ExtraMethods {
		if em.ArgType != "" {
			// Setter method
			o.LL("func (h *stdHeaders) %s(%s %s) {", em.Name, em.ArgName, em.ArgType)
			if em.Lock == "write" {
				o.L("h.mu.Lock()")
				o.L("defer h.mu.Unlock()")
			}
			o.L("h.%s = %s", em.Field, em.ArgName)
			o.L("}")
		} else {
			// Getter method
			o.LL("func (h *stdHeaders) %s() %s{", em.Name, em.Returns)
			if em.Lock == "read" {
				o.L("h.mu.RLock()")
				o.L("defer h.mu.RUnlock()")
			}
			o.L("return h.%s", em.Field)
			o.L("}")
		}
	}

	// PrivateParams
	o.LL("func (h *stdHeaders) PrivateParams() map[string]any {")
	o.L("h.mu.RLock()")
	o.L("defer h.mu.RUnlock()")
	o.L("return h.privateParams")
	o.L("}")

	// Has
	caseCfg := jwxcodegen.CaseConfig{
		Fields:  obj.Fields(),
		KeyName: headerKeyName,
	}
	o.LL("func (h *stdHeaders) Has(name string) bool {")
	o.L("h.mu.RLock()")
	o.L("defer h.mu.RUnlock()")
	o.L("switch name {")
	jwxcodegen.GenerateHasCases(o, caseCfg)
	o.L("default:")
	o.L("_, ok := h.privateParams[name]")
	o.L("return ok")
	o.L("}")
	o.L("}")

	// Field
	o.LL("func (h *stdHeaders) Field(name string) (any, bool) {")
	o.L("h.mu.RLock()")
	o.L("defer h.mu.RUnlock()")
	o.L("switch name {")
	jwxcodegen.GenerateFieldCases(o, caseCfg, headerFieldIsIndirect)
	o.L("default:")
	o.L("v, ok := h.privateParams[name]")
	o.L("return v, ok")
	o.L("}") // end switch name
	o.L("}") // func (h *stdHeaders) Field(name string) (any, bool)

	// Set
	o.LL("func (h *stdHeaders) Set(name string, value any) error {")
	o.L("h.mu.Lock()")
	o.L("defer h.mu.Unlock()")
	o.L("return h.setNoLock(name, value)")
	o.L("}")

	// setNoLock
	// Build skip set for fields with key_algorithm_cast (custom handling).
	setCaseSkip := make(map[string]struct{})
	for _, f := range obj.Fields() {
		if f.Bool(`key_algorithm_cast`) {
			setCaseSkip[f.Name(false)] = struct{}{}
		}
	}
	setCaseCfg := jwxcodegen.CaseConfig{
		Fields:  obj.Fields(),
		KeyName: headerKeyName,
		Skip:    setCaseSkip,
	}
	o.LL("func (h *stdHeaders) setNoLock(name string, value any) error {")
	o.L("switch name {")
	// Emit custom cases for fields with key_algorithm_cast (e.g., JWS algorithm).
	for _, f := range obj.Fields() {
		if !f.Bool(`key_algorithm_cast`) {
			continue
		}
		o.L("case %sKey:", f.Name(true))
		o.L(`alg, err := jwa.KeyAlgorithmFrom(value)`)
		o.L(`if err != nil {`)
		o.L(`return fmt.Errorf("invalid value for %%s key: %%w", %sKey, err)`, f.Name(true))
		o.L(`}`)
		o.L(`if salg, ok := alg.(jwa.SignatureAlgorithm); ok {`)
		o.L(`h.%s = &salg`, f.Name(false))
		o.L(`return nil`)
		o.L(`}`)
		o.L(`return fmt.Errorf("expecte jwa.SignatureAlgorithm, received %%T", alg)`)
	}
	jwxcodegen.GenerateSetCases(o, setCaseCfg, headerFieldIsIndirect)
	o.L("default:")
	o.L("if h.privateParams == nil {")
	o.L("h.privateParams = map[string]any{}")
	o.L("}") // end if h.privateParams == nil
	o.L("h.privateParams[name] = value")
	o.L("}") // end switch name
	o.L("return nil")
	o.L("}")

	// Remove
	o.LL("func (h *stdHeaders) Remove(key string) error {")
	o.L("h.mu.Lock()")
	o.L("defer h.mu.Unlock()")
	o.L("switch key {")
	jwxcodegen.GenerateRemoveCases(o, caseCfg)
	o.L("default:")
	o.L("delete(h.privateParams, key)")
	o.L("}")
	o.L("return nil") // currently unused, but who knows
	o.L("}")

	// UnmarshalJSON
	o.LL("func (h *stdHeaders) UnmarshalJSON(buf []byte) error {")
	o.L("h.mu.Lock()")
	o.L("defer h.mu.Unlock()")
	o.L("h.clear()")
	o.L("dec := json.NewDecoder(bytes.NewReader(buf))")
	o.L("tok, err := dec.ReadToken()")
	o.L("if err != nil {")
	o.L("return fmt.Errorf(`error reading token: %%w`, err)")
	o.L("}")
	o.L("if tok.Kind() != '{' {")
	o.L("return fmt.Errorf(`expected '{' but got '%%c'`, tok.Kind())")
	o.L("}")
	o.L("for dec.PeekKind() != '}' {")
	o.L("tok, err := dec.ReadToken()")
	o.L("if err != nil {")
	o.L("return fmt.Errorf(`error reading token: %%w`, err)")
	o.L("}")
	o.L("switch tok.String() {")

	jwxcodegen.GenerateUnmarshalCases(o, caseCfg, "nil")
	o.L("default:")
	o.L("fieldName := tok.String()")
	o.L("raw, err := dec.ReadValue()")
	o.L("if err != nil {")
	o.L("return fmt.Errorf(`could not read value for field %%s: %%w`, fieldName, err)")
	o.L("}")
	o.L("decoded, err := registry.Decode(fieldName, raw)")
	o.L("if err != nil {")
	o.L("return err")
	o.L("}")
	o.L("h.setNoLock(fieldName, decoded)")
	o.L("}")
	o.L("}")
	o.L("// consume closing '}'")
	o.L("if _, err := dec.ReadToken(); err != nil {")
	o.L("return fmt.Errorf(`error reading closing token: %%w`, err)")
	o.L("}")
	if cfg.StoreRawOnUnmarshal {
		o.L("h.raw = buf")
	}
	o.L("return nil")
	o.L("}")

	// Keys
	jwxcodegen.GenerateKeysMethod(o, jwxcodegen.KeysConfig{
		MethodConfig: jwxcodegen.MethodConfig{
			ReceiverName:       "h",
			StructName:         "stdHeaders",
			Fields:             obj.Fields(),
			KeyName:            headerKeyName,
			PrivateParamsField: "privateParams",
		},
	})

	// cloneFrom
	o.LL("func (dst *stdHeaders) cloneFrom(src *stdHeaders) {")
	o.L("src.mu.RLock()")
	o.L("defer src.mu.RUnlock()")
	o.L("dst.mu.Lock()")
	o.L("defer dst.mu.Unlock()")
	for _, f := range obj.Fields() {
		fname := f.Name(false)
		o.L("if src.%s != nil {", fname)
		if strings.HasPrefix(f.Type(), "[]") {
			o.L("dst.%s = slices.Clone(src.%s)", fname, fname)
		} else if jwxcodegen.IsPointer(f) && f.Bool(`noDeref`) {
			o.L("dst.%s = src.%s", fname, fname)
		} else if jwxcodegen.IsPointer(f) {
			// pointer type without noDeref -- shallow copy (e.g., jwk.Key interface, *cert.Chain in jwe)
			o.L("dst.%s = src.%s", fname, fname)
		} else if jwxcodegen.FieldStorageTypeIsIndirect(f) {
			o.L("tmp := *(src.%s)", fname)
			o.L("dst.%s = &tmp", fname)
		} else {
			o.L("dst.%s = src.%s", fname, fname)
		}
		o.L("} else {")
		o.L("dst.%s = nil", fname)
		o.L("}")
	}
	o.L("if len(src.privateParams) > 0 {")
	o.L("dst.privateParams = make(map[string]any, len(src.privateParams))")
	o.L("for k, v := range src.privateParams {")
	o.L("dst.privateParams[k] = v")
	o.L("}")
	o.L("} else {")
	o.L("dst.privateParams = nil")
	o.L("}")
	if headerHasExtraField(cfg, "raw") {
		o.L("dst.raw = slices.Clone(src.raw)")
	}
	o.L("}")

	// fieldPair type and pool for MarshalJSON
	o.LL("type fieldPair struct {")
	o.L("Name  string")
	o.L("Value any")
	o.L("}")
	o.LL("var fieldPairPool = sync.Pool{")
	o.L("New: func() any {")
	o.L("return make([]fieldPair, 0, 16)")
	o.L("},")
	o.L("}")
	o.LL("func getFieldPairList() []fieldPair {")
	o.L("//nolint:forcetypeassert")
	o.L("return fieldPairPool.Get().([]fieldPair)")
	o.L("}")
	o.LL("func putFieldPairList(list []fieldPair) {")
	o.L("list = list[:0]")
	o.L("fieldPairPool.Put(list) //nolint:staticcheck")
	o.L("}")
	o.LL("func fieldPairLess(a, b fieldPair) int {")
	o.L("return cmp.Compare(a.Name, b.Name)")
	o.L("}")

	// MarshalJSON
	o.LL("func (h *stdHeaders) MarshalJSON() ([]byte, error) {")
	o.L("pairs := getFieldPairList()")
	o.L("h.mu.RLock()")
	for _, f := range obj.Fields() {
		o.L("if h.%s != nil {", f.Name(false))
		if jwxcodegen.FieldStorageTypeIsIndirect(f) {
			o.L("pairs = append(pairs, fieldPair{Name: %sKey, Value: *(h.%s)})", f.Name(true), f.Name(false))
		} else {
			o.L("pairs = append(pairs, fieldPair{Name: %sKey, Value: h.%s})", f.Name(true), f.Name(false))
		}
		o.L("}")
	}
	o.L("for k, v := range h.privateParams {")
	o.L("pairs = append(pairs, fieldPair{Name: k, Value: v})")
	o.L("}")
	o.L("h.mu.RUnlock()")
	o.L("slices.SortFunc(pairs, fieldPairLess)")

	o.L("buf := pool.BytesBuffer().Get()")
	o.L("defer pool.BytesBuffer().Put(buf)")
	o.L("buf.WriteByte('{')")
	o.L("for i, p := range pairs {")
	o.L("if i > 0 { buf.WriteByte(',') }")
	o.L("fmt.Fprintf(buf, `%%q:`, p.Name)")
	o.L("switch v := p.Value.(type) {")
	o.L("case []byte:")
	o.L("fmt.Fprintf(buf, `%%q`, base64.EncodeToString(v))")
	o.L("default:")
	o.L("valBytes, err := json.Marshal(v)")
	o.L("if err != nil {")
	o.L("return nil, fmt.Errorf(`failed to encode value for field %%s: %%w`, p.Name, err)")
	o.L("}")
	o.L("buf.Write(valBytes)")
	o.L("}")
	o.L("}")
	o.L("buf.WriteByte('}')")
	o.L("putFieldPairList(pairs)")
	o.L("ret := make([]byte, buf.Len())")
	o.L("copy(ret, buf.Bytes())")
	o.L("return ret, nil")
	o.L("}")

	if err := o.WriteFile(cfg.OutputFile, codegen.WithFormatCode(true)); err != nil {
		if cfe, ok := err.(codegen.CodeFormatError); ok {
			fmt.Fprint(os.Stderr, cfe.Source())
		}
		return fmt.Errorf(`failed to write to %s: %w`, cfg.OutputFile, err)
	}
	return nil
}
