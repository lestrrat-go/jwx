package main

import (
	"bytes"
	"fmt"
	"os"

	"github.com/lestrrat-go/codegen"
)

type readfileDefinition struct {
	Filename   string
	Package    string
	ReturnType string
}

func runReadFile(args []string) error {
	definitions := []readfileDefinition{
		{
			Package:    "jwk",
			ReturnType: "Set",
			Filename:   "jwk/io_gen.go",
		},
		{
			Package:    "jws",
			ReturnType: "*Message",
			Filename:   "jws/io_gen.go",
		},
		{
			Package:    "jwe",
			ReturnType: "*Message",
			Filename:   "jwe/io_gen.go",
		},
		{
			Package:    "jwt",
			ReturnType: "Token",
			Filename:   "jwt/io_gen.go",
		},
	}

	for _, def := range definitions {
		if err := generateReadFile(def); err != nil {
			return err
		}
	}
	return nil
}

func generateReadFile(def readfileDefinition) error {
	var buf bytes.Buffer
	o := codegen.NewOutput(&buf)

	o.LL("// Code generated by internal/jwxcodegen/cmd/jwxcodegen (generate-readfile). DO NOT EDIT.")
	o.LL("package %s", def.Package)

	o.WriteImports("io/fs", "os")

	o.LL("// ParseFS opens path on fsys and parses the contents.")
	o.L("func ParseFS(fsys fs.FS, path string, options ...ParseOption) (%s, error) {", def.ReturnType)
	o.L("f, err := fsys.Open(path)")
	o.L("if err != nil {")
	o.L("return nil, err")
	o.L("}")
	o.L("defer f.Close()")
	o.LL("return ParseReader(f, options...)")
	o.L("}")

	o.LL("// ReadFile opens path with os.Open and parses the contents. It accepts")
	o.L("// any path os.Open accepts, including absolute paths.")
	o.L("//")
	o.L("// Deprecated: prefer ParseFS, which works with any fs.FS (e.g. os.DirFS,")
	o.L("// embed.FS, testing/fstest). ReadFile is retained for v3 source compatibility.")
	o.L("func ReadFile(path string, options ...ParseOption) (%s, error) {", def.ReturnType)
	o.L("f, err := os.Open(path)")
	o.L("if err != nil {")
	o.L("return nil, err")
	o.L("}")
	o.L("defer f.Close()")
	o.LL("return ParseReader(f, options...)")
	o.L("}")
	if err := o.WriteFile(def.Filename, codegen.WithFormatCode(true)); err != nil {
		if cfe, ok := err.(codegen.CodeFormatError); ok {
			fmt.Fprint(os.Stderr, cfe.Source())
		}
		return fmt.Errorf(`failed to write to %s: %w`, def.Filename, err)
	}
	return nil
}
